// The loader is written so that it compiles in both fixed and free
// format: code in columns 8 to 72, *> comments, no continuation lines.
const (
	area  = "       "     // column 8
	stmt  = "           " // column 12
	width = 72
)

type emitter struct {
	b strings.Builder
}

// line writes a statement, breaking it at spaces outside literals when
// it would pass column 72.
func (e *emitter) line(indent int, s string) {
	pad := stmt + strings.Repeat("    ", indent)
	for len(pad)+len(s) > width {
		cut := -1
		inLit := false
		for i := 0; i < len(s) && len(pad)+i <= width; i++ {
			switch {
			case s[i] == '"':
				inLit = !inLit
			case s[i] == ' ' && !inLit:
				cut = i
			}
		}
		if cut <= 0 {
			break // nothing to break at; Loader reports the long line
		}
		e.b.WriteString(pad + s[:cut] + "\n")
		s = s[cut+1:]
		if !strings.HasPrefix(pad, stmt+strings.Repeat("    ", indent)+"  ") {
			pad += "  "
		}
	}
	e.b.WriteString(pad + s + "\n")
}

func (e *emitter) para(name string) {
	e.b.WriteString(area + name + ".\n")
}

func (e *emitter) comment(s string) {
	e.b.WriteString(strings.TrimRight("      *> "+s, " ") + "\n")
}

// move writes MOVE literal TO target, splitting a long literal into
// parts joined with &.
func (e *emitter) move(indent int, value, target string) {
	if value == "" {
		e.line(indent, "MOVE SPACES TO "+target)
		return
	}
	col := len(stmt) + 4*indent
	one := "MOVE " + cobolLiteral(value) + " TO " + target
	if col+len(one) <= width {
		e.line(indent, one)
		return
	}
	parts := chunks(value, width-col-8)
	for i, p := range parts {
		if i == 0 {
			e.line(indent, "MOVE "+cobolLiteral(p))
		} else {
			e.line(indent, "  & "+cobolLiteral(p))
		}
	}
	e.line(indent, "  TO "+target)
}

// problem writes the statements that report a problem.
func (e *emitter) problem(indent int, msg, code string) {
	e.move(indent, msg, "DC-MSG")
	e.line(indent, fmt.Sprintf("MOVE %q TO DC-CODE", code))
	e.line(indent, "PERFORM DC-PROBLEM")
}

// cobolLiteral quotes s, doubling quotes inside.
func cobolLiteral(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

// chunks splits s into pieces of at most n bytes once quoted, keeping
// UTF-8 sequences whole, and after a space where there is one.
func chunks(s string, n int) []string {
	out := rawChunks(s, n)
	for i := 0; i+1 < len(out); i++ {
		if j := strings.LastIndexByte(out[i], ' '); j > 0 && j < len(out[i])-1 {
			moved := out[i][j+1:]
			if len(moved)+len(out[i+1]) <= n {
				out[i], out[i+1] = out[i][:j+1], moved+out[i+1]
			}
		}
	}
	return out
}

func rawChunks(s string, n int) []string {
	var out []string
	var cur strings.Builder
	size := 0
	for _, r := range s {
		w := len(string(r))
		if r == '"' {
			w = 2
		}
		if size+w > n && cur.Len() > 0 {
			out = append(out, cur.String())
			cur.Reset()
			size = 0
		}
		cur.WriteRune(r)
		size += w
	}
	return append(out, cur.String())
}

func picText(v *Var) string {
	p := v.Pic
	switch {
	case v.Double:
		return "floating-point"
	case p.Alpha:
		return fmt.Sprintf("PIC X(%d)", p.Size)
	}
	s := ""
	if p.Signed {
		s = "S"
	}
	s += fmt.Sprintf("9(%d)", p.IntDigits)
	if p.Frac > 0 {
		s += fmt.Sprintf("V9(%d)", p.Frac)
	}
	return "PIC " + s
}

// Loader returns the COBOL source of the loader program.
func (c *Config) Loader() ([]byte, error) {
	for _, v := range c.Vars {
		for _, d := range v.Default {
			for _, r := range d {
				if r < 0x20 {
					return nil, fmt.Errorf("%s:%d: %s: a default with control characters cannot be written as a COBOL literal", c.Copybook, v.Line, v.Field)
				}
			}
		}
	}
	paras := c.paragraphs()
	if err := c.checkNames(paras); err != nil {
		return nil, err
	}
	e := &emitter{}
	e.comment("Code generated by docuconf-cobol. DO NOT EDIT.")
	e.comment("Source: " + c.Copybook + ". Change the copybook and run")
	e.comment("docuconf-cobol generate again.")
	e.comment("")
	e.comment(fmt.Sprintf("CALL %q USING %s reads the", c.Program, c.Record))
	e.comment("environment into the record and converts each value. On a")
	e.comment("problem it prints every problem on stderr, writes them to")
	e.comment("the termination log and sets RETURN-CODE to 1. Run the")
	e.comment("program under docuconf exec, which also checks the rules")
	e.comment("COBOL cannot (patterns, JSON Schemas, files) first.")
	e.b.WriteString(area + "IDENTIFICATION DIVISION.\n")
	e.b.WriteString(area + "PROGRAM-ID. " + c.Program + ".\n")
	e.b.WriteString(area + "ENVIRONMENT DIVISION.\n")
	e.b.WriteString(area + "INPUT-OUTPUT SECTION.\n")
	e.b.WriteString(area + "FILE-CONTROL.\n")
	e.line(0, "SELECT DC-TLOG ASSIGN TO DC-TLOG-PATH")
	e.line(1, "ORGANIZATION IS LINE SEQUENTIAL")
	e.line(1, "FILE STATUS IS DC-TLOG-STATUS.")
	e.b.WriteString(area + "DATA DIVISION.\n")
	e.b.WriteString(area + "FILE SECTION.\n")
	e.b.WriteString(area + "FD  DC-TLOG.\n")
	e.b.WriteString(area + "01  DC-TLOG-LINE            PIC X(256).\n")
	e.b.WriteString(area + "WORKING-STORAGE SECTION.\n")
	if c.Runtime == "copy" {
		e.b.WriteString(area + "COPY DCRTWS.\n")
	} else {
		e.b.WriteString(copybooks.WorkingStorage)
	}
	e.b.WriteString(area + "LINKAGE SECTION.\n")
	if c.Wrap {
		e.b.WriteString(area + "01  " + c.Record + ".\n")
	}
	e.b.WriteString(area + "COPY " + copyName(c.Copybook) + ".\n")
	e.b.WriteString(area + "PROCEDURE DIVISION USING " + c.Record + ".\n")
	e.para("DC-MAIN")
	e.line(0, "MOVE 0 TO DC-PROBLEMS")
	for _, v := range c.Vars {
		e.line(0, "PERFORM "+paras[v.Field])
	}
	for _, f := range c.Files {
		e.line(0, "PERFORM "+paras[f.Field])
	}
	e.line(0, "IF DC-PROBLEMS = 0")
	e.line(1, "MOVE 0 TO RETURN-CODE")
	e.line(0, "ELSE")
	e.line(1, "PERFORM DC-REPORT")
	e.line(1, "MOVE 1 TO RETURN-CODE")
	e.line(0, "END-IF")
	e.line(0, "GOBACK.")
	for _, v := range c.Vars {
		e.b.WriteByte('\n')
		c.loadVar(e, paras, v)
	}
	for _, f := range c.Files {
		e.b.WriteByte('\n')
		loadFile(e, paras[f.Field], f)
	}
	for _, g := range c.grammars() {
		e.b.WriteByte('\n')
		g.emit(e)
	}
	e.b.WriteByte('\n')
	if c.Runtime == "copy" {
		e.b.WriteString(area + "COPY DCRTPD.\n")
	} else {
		e.b.WriteString(copybooks.Procedures)
	}
	e.b.WriteString(area + "END PROGRAM " + c.Program + ".\n")
	out := e.b.String()
	for i, l := range strings.Split(out, "\n") {
		if len(l) > width {
			return nil, fmt.Errorf("internal error: generated line %d is longer than 72 columns: %s", i+1, l)
		}
	}
	return []byte(out), nil
}

// copyName is how the loader's COPY statement names the copybook: as a
// member name (COPY ORDCFGC.) when the file is a member name with a
// copybook extension cobc searches by default, else as a quoted file
// name.
func copyName(file string) string {
	ext := filepath.Ext(file)
	base := strings.TrimSuffix(file, ext)
	if memberRe.MatchString(base) && slices.Contains([]string{".cpy", ".CPY", ".cbl", ".CBL", ".cob", ".COB"}, ext) {
		return base
	}
	return cobolLiteral(file)
}

// paragraphs names the paragraph that loads each field after the field,
// so adding a field does not rename the others: DCV-<field> for a
// variable, DCI-<field> for a list's items, DCF-<field> for a file input.
// A name that would pass 30 characters is shortened and numbered.
func (c *Config) paragraphs() map[string]string {
	out := map[string]string{}
	name := func(prefix, field string, n int) string {
		s := prefix + field
		if len(s) > 30 {
			s = fmt.Sprintf("%s%s-%d", prefix, strings.TrimRight(field[:30-len(prefix)-5], "-"), n)
		}
		return s
	}
	for i, v := range c.Vars {
		out[v.Field] = name("DCV-", v.Field, i+1)
		out[v.Field+" ITEM"] = name("DCI-", v.Field, i+1)
	}
	for i, f := range c.Files {
		out[f.Field] = name("DCF-", f.Field, i+1)
	}
	return out
}

// checkNames reports a data name in the copybook that the loader also
// uses: its working storage, its paragraphs and its own PROGRAM-ID. cobc
// would otherwise fail on the generated loader ("ambiguous").
func (c *Config) checkNames(paras map[string]string) error {
	reserved := map[string]string{c.Program: "the loader's PROGRAM-ID"}
	ws, _, _ := copybook.Parse("DCRTWS.cpy", copybooks.WorkingStorage, copybook.Fixed)
	var walk func(e *copybook.Entry)
	walk = func(e *copybook.Entry) {
		reserved[e.Name] = "a name in the loader's working storage (DCRTWS)"
		for _, ch := range e.Children {
			walk(ch)
		}
	}
	for _, r := range ws {
		walk(r)
	}
	for _, n := range []string{"DC-TLOG", "DC-TLOG-LINE"} {
		reserved[n] = "the loader's termination log file"
	}
	for _, m := range paraRe.FindAllStringSubmatch(copybooks.Procedures, -1) {
		reserved[m[1]] = "a paragraph of the loader's runtime (DCRTPD)"
	}
	reserved["DC-MAIN"] = "a paragraph of the loader"
	for _, g := range grammars {
		reserved[g.para] = "a paragraph of the loader"
	}
	for _, p := range paras {
		reserved[p] = "a paragraph of the loader"
	}
	var ps []string
	names := make([]string, 0, len(c.names))
	for n := range c.names {
		names = append(names, n)
	}
	slices.SortFunc(names, func(a, b string) int { return c.names[a] - c.names[b] })
	for _, n := range names {
		if what, ok := reserved[n]; ok {
			ps = append(ps, fmt.Sprintf("%s:%d: %s is %s; rename it (names starting DC are the loader's)", c.Copybook, c.names[n], n, what))
		}
	}
	if c.Wrap && c.names[c.Record] != 0 {
		ps = append(ps, fmt.Sprintf("%s:%d: %s is the name of the record the loader declares around the fields; pass another with -record", c.Copybook, c.names[c.Record], c.Record))
	}
	if len(ps) > 0 {
		return &Error{ps}
	}
	return nil
}

var paraRe = regexp.MustCompile(`(?m)^       (DC-[A-Z0-9-]+)\.$`)

func (c *Config) loadVar(e *emitter, paras map[string]string, v *Var) {
	e.comment(fmt.Sprintf("%s into %s", v.Env, v.Field))
	e.para(paras[v.Field])
	e.move(0, v.Env, "DC-NAME")
	if v.isList() {
		c.loadList(e, paras[v.Field+" ITEM"], v)
		return
	}
	e.line(0, "PERFORM DC-GET-ENV")
	if v.Type != tString {
		// An empty value is unset for every type but string.
		e.line(0, "IF DC-LEN = 0")
		e.line(1, `MOVE "N" TO DC-SET`)
		e.line(0, "END-IF")
	}
	e.line(0, `IF DC-SET = "N"`)
	e.line(1, "INITIALIZE "+v.Field)
	switch {
	case v.Required:
		e.problem(1, "is required but not set", "missing_required")
	case v.Default != nil:
		defaultScalar(e, 1, v, v.Field)
	}
	if v.Present != "" {
		if v.Default != nil {
			e.line(1, `MOVE "Y" TO `+v.Present)
		} else {
			e.line(1, `MOVE "N" TO `+v.Present)
		}
	}
	e.line(0, "ELSE")
	deprecationWarning(e, 1, v)
	ind := 1
	if v.Secret {
		e.line(1, "PERFORM DC-CHECK-REF")
		e.line(1, `IF DC-REF = "Y"`)
		e.problem(2, refMsg, "invalid_type")
		e.line(1, "ELSE")
		ind = 2
	}
	storeScalar(e, ind, v, v.Field, v.Field)
	if v.Secret {
		e.line(1, "END-IF")
	}
	if v.Present != "" {
		e.line(1, `MOVE "Y" TO `+v.Present)
	}
	e.line(0, "END-IF.")
}

// refMsg reports a secret that still holds an injector reference
// (SPEC §4.5.1), without the reference.
const refMsg = "holds an unresolved injector reference (vault:, op:// or ref+); the injector that should resolve it did not run"

// defaultScalar moves the default into target.
func defaultScalar(e *emitter, ind int, v *Var, target string) {
	d := v.Default[0]
	switch v.Type {
	case tString, tURL, tEnum, tJSON:
		e.move(ind, d, target)
	case tInt, tFloat:
		e.line(ind, "MOVE "+d+" TO "+target)
	case tBool:
		e.line(ind, "MOVE "+boolValue(v, slices.Contains([]string{"true", "y", "1"}, strings.ToLower(d)))+" TO "+target)
	case tDuration:
		e.line(ind, "MOVE "+durationValue(d, v.UnitNs)+" TO "+target)
	}
}

func boolValue(v *Var, b bool) string {
	switch {
	case v.Pic.Alpha && b:
		return `"Y"`
	case v.Pic.Alpha:
		return `"N"`
	case b:
		return "1"
	}
	return "0"
}

// durationValue is a duration default in the field's unit.
func durationValue(d string, unitNs int64) string {
	ns, _ := parseGoDuration(d)
	r := new(big.Rat).SetFrac(big.NewInt(ns), big.NewInt(unitNs))
	if r.IsInt() {
		return r.Num().String()
	}
	return strings.TrimRight(r.FloatString(9), "0")
}

// storeScalar converts DC-RAW(1:DC-LEN) and stores it in target. label
// names the field in messages.
func storeScalar(e *emitter, ind int, v *Var, target, label string) {
	typ := v.Type
	if v.isList() {
		typ = v.Items
	}
	// A value must have SPEC section 5's exact form for its type before
	// it is converted: the conversions below are more lenient.
	if g := grammarOf(v); g != nil {
		e.line(ind, "PERFORM "+g.para)
		e.line(ind, `IF DC-RX-OK = "N"`)
		e.problem(ind+1, g.msg, "invalid_type")
		e.line(ind, "ELSE")
		storeTyped(e, ind+1, v, typ, target, label)
		e.line(ind, "END-IF")
		return
	}
	storeTyped(e, ind, v, typ, target, label)
}

// storeTyped converts DC-RAW(1:DC-LEN), of scalar type typ, into target.
func storeTyped(e *emitter, ind int, v *Var, typ, target, label string) {
	fits := fmt.Sprintf("does not fit in %s (%s)", label, picText(v))
	switch typ {
	case tString, tURL, tEnum, tJSON:
		e.line(ind, fmt.Sprintf("IF DC-LEN > %d", v.Pic.Size))
		e.problem(ind+1, fits, "out_of_range")
		ends := valueChecks(e, ind, v, typ)
		e.line(ind, "ELSE")
		e.line(ind+1, "MOVE SPACES TO "+target)
		e.line(ind+1, "IF DC-LEN > 0")
		e.line(ind+2, "MOVE DC-RAW(1:DC-LEN) TO "+target)
		e.line(ind+1, "END-IF")
		if typ == tEnum {
			e.line(ind+1, "EVALUATE "+target)
			for _, val := range v.Values {
				e.line(ind+2, "WHEN "+cobolLiteral(val))
			}
			e.line(ind+3, "CONTINUE")
			e.line(ind+2, "WHEN OTHER")
			e.problem(ind+3, "is not one of the enum's values", "not_in_enum")
			e.line(ind+1, "END-EVALUATE")
		}
		for i := 0; i < ends; i++ {
			e.line(ind, "END-IF")
		}
		e.line(ind, "END-IF")
	case tInt:
		e.line(ind, "PERFORM DC-PARSE-INT")
		e.line(ind, `IF DC-OK = "Y"`)
		ind2 := ind + 1
		if !v.Pic.Signed {
			e.line(ind+1, "IF DC-INT < 0")
			e.problem(ind+2, fmt.Sprintf("is negative, and %s is unsigned", label), "out_of_range")
			e.line(ind+1, "ELSE")
			ind2++
		}
		e.line(ind2, "COMPUTE "+target+" = DC-INT")
		e.line(ind2+1, "ON SIZE ERROR")
		e.problem(ind2+2, fits, "out_of_range")
		e.line(ind2, "END-COMPUTE")
		var lo, hi string
		if v.Min != nil {
			lo = v.Min.String()
		}
		if v.Max != nil {
			hi = v.Max.String()
		}
		boundChecks(e, ind2, "DC-INT", lo, hi, v.Type == tList)
		if !v.Pic.Signed {
			e.line(ind+1, "END-IF")
		}
		e.line(ind, "END-IF")
	case tFloat:
		num := "FUNCTION NUMVAL-F(DC-TMP(1:DC-TMP-LEN))"
		e.line(ind, "PERFORM DC-PARSE-FLOAT")
		e.line(ind, `IF DC-OK = "Y"`)
		ind2 := ind + 1
		if !v.Pic.Signed {
			e.line(ind+1, "IF "+num+" < 0")
			e.problem(ind+2, fmt.Sprintf("is negative, and %s is unsigned", label), "out_of_range")
			e.line(ind+1, "ELSE")
			ind2++
		}
		e.line(ind2, "COMPUTE "+target+" =")
		e.line(ind2+1, num)
		e.line(ind2+1, "ON SIZE ERROR")
		e.problem(ind2+2, fits, "out_of_range")
		e.line(ind2, "END-COMPUTE")
		if !v.Double {
			e.line(ind2, `IF DC-OK = "Y" AND `+target)
			e.line(ind2+1, "NOT = "+num)
			e.problem(ind2+1, fmt.Sprintf("has more decimal places than %s holds", label), "out_of_range")
			e.line(ind2, "END-IF")
		}
		var lo, hi string
		if v.MinRat != nil {
			lo = string(ratNumber(v.MinRat, v.Pic.Frac))
		}
		if v.MaxRat != nil {
			hi = string(ratNumber(v.MaxRat, v.Pic.Frac))
		}
		boundChecks(e, ind2, num, lo, hi, false)
		if !v.Pic.Signed {
			e.line(ind+1, "END-IF")
		}
		e.line(ind, "END-IF")
	case tBool:
		e.line(ind, "PERFORM DC-PARSE-BOOL")
		e.line(ind, `IF DC-OK = "Y"`)
		if v.Pic.Alpha {
			e.line(ind+1, "MOVE DC-BOOL TO "+target)
		} else {
			e.line(ind+1, `IF DC-BOOL = "Y"`)
			e.line(ind+2, "MOVE 1 TO "+target)
			e.line(ind+1, "ELSE")
			e.line(ind+2, "MOVE 0 TO "+target)
			e.line(ind+1, "END-IF")
		}
		e.line(ind, "END-IF")
	case tDuration:
		e.line(ind, fmt.Sprintf("MOVE %q TO DC-ENC", v.Encoding))
		e.line(ind, "PERFORM DC-PARSE-DURATION")
		e.line(ind, `IF DC-OK = "Y"`)
		e.line(ind+1, fmt.Sprintf("MOVE %d TO DC-UNIT-NS", v.UnitNs))
		e.line(ind+1, "COMPUTE DC-CHK = DC-NS / DC-UNIT-NS")
		ind2 := ind + 1
		if !v.Pic.Signed {
			e.line(ind+1, "IF DC-CHK < 0")
			e.problem(ind+2, fmt.Sprintf("is negative, and %s is unsigned", label), "out_of_range")
			e.line(ind+1, "ELSE")
			ind2++
		}
		e.line(ind2, "COMPUTE "+target+" = DC-CHK")
		e.line(ind2+1, "ON SIZE ERROR")
		e.problem(ind2+2, fits, "out_of_range")
		e.line(ind2, "END-COMPUTE")
		e.line(ind2, `IF DC-OK = "Y" AND `+target)
		e.line(ind2+1, "NOT = DC-CHK")
		e.problem(ind2+1, fmt.Sprintf("is finer than the %s %s counts in", v.Unit, label), "out_of_range")
		e.line(ind2, "END-IF")
		if v.MinNs != nil {
			durationBound(e, ind2, "<", *v.MinNs, "is below min "+formatDuration(*v.MinNs))
		}
		if v.MaxNs != nil {
			durationBound(e, ind2, ">", *v.MaxNs, "is above max "+formatDuration(*v.MaxNs))
		}
		if !v.Pic.Signed {
			e.line(ind+1, "END-IF")
		}
		e.line(ind, "END-IF")
	}
}

// valueChecks writes the checks of a string, url or json value in
// DC-RAW(1:DC-LEN) that fits its field: a url's form and scheme, a json
// value's syntax, and length limits in characters. Each check is an
// ELSE IF after the field-size check, so a value gets one problem; it
// returns how many END-IFs to close.
func valueChecks(e *emitter, ind int, v *Var, typ string) int {
	ends := 0
	check := func(cond, msg, code string) {
		e.line(ind, "ELSE")
		e.line(ind, "IF "+cond)
		e.problem(ind+1, msg, code)
		ends++
	}
	switch typ {
	case tURL:
		e.line(ind, "ELSE")
		e.line(ind, "PERFORM DC-CHECK-URL")
		e.line(ind, `IF DC-OK = "N"`)
		e.problem(ind+1, "is not a URL of the form scheme://...", "invalid_type")
		ends++
		if len(v.Schemes) > 0 {
			var conds []string
			for _, sc := range v.Schemes {
				conds = append(conds, fmt.Sprintf("(DC-Q = %d AND FUNCTION LOWER-CASE(DC-RAW(1:DC-Q)) = %s)", len(sc), cobolLiteral(strings.ToLower(sc))))
			}
			check("NOT ("+strings.Join(conds, " OR ")+")", "scheme is not one of "+strings.Join(v.Schemes, ", "), "invalid_scheme")
		}
	case tJSON:
		e.line(ind, "ELSE")
		e.line(ind, "PERFORM DC-CHECK-JSON")
		e.line(ind, `IF DC-OK = "N"`)
		e.problem(ind+1, "is not valid JSON", "invalid_type")
		ends++
	}
	lo, hi, what, minW, maxW := v.MinLen, v.MaxLen, "is", "minLength", "maxLength"
	switch v.Type {
	case tList:
		lo, hi, what, minW, maxW = v.ItemMinLen, v.ItemMaxLen, "has an item", "itemMinLength", "itemMaxLength"
	case tKeySet:
		lo, hi, what, minW, maxW = v.ItemMinLen, v.ItemMaxLen, "has a key", "keyMinLength", "keyMaxLength"
	}
	if typ != tEnum && (lo != nil || hi != nil) {
		e.line(ind, "ELSE")
		e.line(ind, "PERFORM DC-COUNT-CHARS")
		if v.Type == tKeySet {
			// An empty key, a stray separator, is out of range whatever
			// keyMinLength says. SPEC section 4.3 words its message
			// exactly, naming the key by its 1-based position as
			// received: "key 2 is empty" for "old,".
			e.line(ind, "IF DC-CHARS = 0")
			e.line(ind+1, "MOVE DC-K TO DC-IDX-ED")
			e.line(ind+1, "MOVE SPACES TO DC-MSG")
			e.line(ind+1, `STRING "key " FUNCTION TRIM(DC-IDX-ED) " is empty"`)
			e.line(ind+2, "DELIMITED BY SIZE INTO DC-MSG")
			e.line(ind+1, "END-STRING")
			e.line(ind+1, `MOVE "out_of_range" TO DC-CODE`)
			e.line(ind+1, "PERFORM DC-PROBLEM")
			ends++
			if *lo > 1 || hi != nil {
				e.line(ind, "ELSE")
			}
			if *lo == 1 {
				lo = nil
			}
		}
		if lo != nil {
			e.line(ind, fmt.Sprintf("IF DC-CHARS < %d", *lo))
			e.problem(ind+1, fmt.Sprintf("%s shorter than %s %d characters", what, minW, *lo), "out_of_range")
			ends++
			if hi != nil {
				e.line(ind, "ELSE")
			}
		}
		if hi != nil {
			e.line(ind, fmt.Sprintf("IF DC-CHARS > %d", *hi))
			e.problem(ind+1, fmt.Sprintf("%s longer than %s %d characters", what, maxW, *hi), "out_of_range")
			ends++
		}
	}
	if typ == tString && v.Type == tString && v.Pattern != nil {
		// The pattern's program, compiled by generate (regex.go).
		e.line(ind, "ELSE")
		e.table(ind, v.Pattern.insts, "DC-RX-PROG")
		if v.Pattern.ranges != "" {
			e.table(ind, v.Pattern.ranges, "DC-RX-RANGES")
		}
		e.line(ind, fmt.Sprintf("MOVE %d TO DC-RX-N", v.Pattern.n))
		e.line(ind, fmt.Sprintf("MOVE %d TO DC-RX-START", v.Pattern.start))
		e.line(ind, "PERFORM DC-RX-MATCH")
		e.line(ind, `IF DC-RX-OK = "N"`)
		e.problem(ind+1, "does not match its pattern", "pattern_mismatch")
		ends++
	}
	return ends
}

// table moves data, a table's text, into target in pieces that fit a
// line.
func (e *emitter) table(ind int, data, target string) {
	for i := 0; i < len(data); i += 40 {
		j := min(i+40, len(data))
		e.line(ind, fmt.Sprintf("MOVE %s TO %s(%d:%d)", cobolLiteral(data[i:j]), target, i+1, j-i))
	}
}

// boundChecks reports a value below lo or above hi (each "" for none).
// The value is not shown: it may be a secret.
func boundChecks(e *emitter, ind int, value, lo, hi string, item bool) {
	what, minW, maxW := "is", "min", "max"
	if item {
		what, minW, maxW = "has an item", "itemMin", "itemMax"
	}
	if lo != "" {
		e.line(ind, `IF DC-OK = "Y" AND `+value+" < "+lo)
		e.problem(ind+1, fmt.Sprintf("%s below %s %s", what, minW, lo), "out_of_range")
		e.line(ind, "END-IF")
	}
	if hi != "" {
		e.line(ind, `IF DC-OK = "Y" AND `+value+" > "+hi)
		e.problem(ind+1, fmt.Sprintf("%s above %s %s", what, maxW, hi), "out_of_range")
		e.line(ind, "END-IF")
	}
}

func durationBound(e *emitter, ind int, op string, ns int64, msg string) {
	e.line(ind, fmt.Sprintf(`IF DC-OK = "Y" AND DC-NS %s %d`, op, ns))
	e.problem(ind+1, msg, "out_of_range")
	e.line(ind, "END-IF")
}

func (c *Config) loadList(e *emitter, itemPara string, v *Var) {
	item := v.Field + "(DC-K)"
	e.line(0, fmt.Sprintf("MOVE %d TO DC-ITEM-LIMIT", v.Occurs))
	if v.Encoding == "indexed" {
		e.line(0, "MOVE DC-PROBLEMS TO DC-PROBLEMS-AT")
		e.line(0, "PERFORM DC-READ-INDEXED")
		e.line(0, "IF DC-PROBLEMS = DC-PROBLEMS-AT")
		e.line(1, "PERFORM DC-INDEXED-GAP")
		e.line(0, "END-IF")
	} else {
		e.line(0, "PERFORM DC-GET-ENV")
		e.line(0, "IF DC-LEN = 0")
		e.line(1, `MOVE "N" TO DC-SET`)
		e.line(0, "END-IF")
	}
	// Every slot is cleared, with the count at the table's size so a
	// DEPENDING ON table can be addressed in full.
	e.line(0, fmt.Sprintf("MOVE %d TO %s", v.Occurs, v.Count))
	e.line(0, "PERFORM VARYING DC-K FROM 1 BY 1")
	e.line(2, fmt.Sprintf("UNTIL DC-K > %d", v.Occurs))
	e.line(1, "INITIALIZE "+item)
	e.line(0, "END-PERFORM")
	e.line(0, `IF DC-SET = "N"`)
	e.line(1, "MOVE 0 TO DC-ITEM-COUNT")
	switch {
	case v.Required:
		e.problem(1, "is required but not set", "missing_required")
	case v.Default != nil:
		for i, d := range v.Default {
			t := fmt.Sprintf("%s(%d)", v.Field, i+1)
			if v.Items == tInt {
				e.line(1, "MOVE "+d+" TO "+t)
			} else {
				e.move(1, d, t)
			}
		}
		e.line(1, fmt.Sprintf("MOVE %d TO DC-ITEM-COUNT", len(v.Default)))
	}
	if v.Present != "" {
		e.line(1, fmt.Sprintf(`MOVE %q TO %s`, map[bool]string{true: "Y", false: "N"}[v.Default != nil], v.Present))
	}
	e.line(0, "ELSE")
	deprecationWarning(e, 1, v)
	split := 1
	if v.Secret && v.Encoding != "indexed" {
		e.line(1, "PERFORM DC-CHECK-REF")
		e.line(1, `IF DC-REF = "Y"`)
		e.problem(2, refMsg, "invalid_type")
		e.line(1, "ELSE")
		split = 2
	}
	switch v.Encoding {
	case "csv":
		e.move(split, v.Separator, "DC-SEP")
		e.line(split, fmt.Sprintf("MOVE %d TO DC-SEP-LEN", len(v.Separator)))
		e.line(split, "PERFORM DC-SPLIT-CSV")
	case "json":
		e.line(split, "PERFORM DC-SPLIT-JSON")
	}
	if split == 2 {
		e.line(1, "END-IF")
	}
	if v.Secret && v.Encoding == "indexed" {
		e.line(1, `MOVE "N" TO DC-REF`)
		e.line(1, "PERFORM VARYING DC-K FROM 1 BY 1")
		e.line(3, `UNTIL DC-K > DC-ITEM-COUNT OR DC-REF = "Y"`)
		e.line(2, "PERFORM DC-ITEM-TO-RAW")
		e.line(2, "PERFORM DC-CHECK-REF")
		e.line(1, "END-PERFORM")
		e.line(1, `IF DC-REF = "Y"`)
		e.problem(2, refMsg, "invalid_type")
		e.line(1, "END-IF")
	}
	e.line(1, `IF DC-OK = "Y"`)
	items, minW, maxW := "items", "minItems", "maxItems"
	if v.Type == tKeySet {
		items, minW, maxW = "keys", "minKeys", "maxKeys"
	}
	if v.MinItems > 0 {
		e.line(2, fmt.Sprintf("IF DC-ITEM-COUNT < %d", v.MinItems))
		e.problem(3, fmt.Sprintf("has too few %s, below %s %d", items, minW, v.MinItems), "too_few_items")
		e.line(2, "END-IF")
	}
	if v.MaxItems > 0 {
		e.line(2, fmt.Sprintf("IF DC-ITEM-COUNT > %d", v.MaxItems))
		e.problem(3, fmt.Sprintf("has too many %s, above %s %d", items, maxW, v.MaxItems), "too_many_items")
		e.line(2, "END-IF")
	}
	e.line(2, "PERFORM VARYING DC-K FROM 1 BY 1")
	e.line(4, "UNTIL DC-K > DC-ITEM-COUNT")
	e.line(3, "PERFORM "+itemPara)
	e.line(2, "END-PERFORM")
	e.line(1, "ELSE")
	e.line(2, "MOVE 0 TO DC-ITEM-COUNT")
	e.line(1, "END-IF")
	if v.Present != "" {
		e.line(1, `MOVE "Y" TO `+v.Present)
	}
	e.line(0, "END-IF")
	e.line(0, "MOVE DC-ITEM-COUNT TO "+v.Count+".")

	e.b.WriteByte('\n')
	e.para(itemPara)
	kind := map[string]string{tString: "S", tInt: "N"}[v.Items]
	if v.Encoding == "json" {
		e.line(0, fmt.Sprintf("IF DC-ITEM-KIND(DC-K) NOT = %q", kind))
		e.problem(1, "has an item of the wrong JSON type", "invalid_type")
		e.line(0, "ELSE")
	}
	e.line(0, "PERFORM DC-ITEM-TO-RAW")
	storeScalar(e, 0, v, item, v.Field)
	if v.Encoding == "json" {
		e.line(0, "END-IF")
	}
	e.b.WriteString(stmt + ".\n")
}

func loadFile(e *emitter, para string, f *FileInput) {
	e.comment(fmt.Sprintf("file input %s: its path into %s", f.Name, f.Field))
	e.para(para)
	if f.PathEnv != "" {
		e.move(0, f.PathEnv, "DC-NAME")
		e.line(0, "PERFORM DC-GET-ENV")
		e.line(0, `MOVE "Y" TO DC-FROM-ENV`)
		e.line(0, `IF DC-SET = "N" OR DC-LEN = 0`)
		e.line(1, `MOVE "N" TO DC-FROM-ENV`)
		e.line(1, "MOVE SPACES TO DC-RAW")
		e.move(1, f.Path, "DC-RAW")
		e.line(1, fmt.Sprintf("MOVE %d TO DC-LEN", len(f.Path)))
		e.line(0, "END-IF")
	} else {
		e.line(0, `MOVE "N" TO DC-FROM-ENV`)
		e.line(0, "MOVE SPACES TO DC-RAW")
		e.move(0, f.Path, "DC-RAW")
		e.line(0, fmt.Sprintf("MOVE %d TO DC-LEN", len(f.Path)))
	}
	e.move(0, f.Name, "DC-BASE")
	e.line(0, "PERFORM DC-BASE-NAME")
	e.line(0, `MOVE "Y" TO DC-OK`)
	e.line(0, "PERFORM DC-APPLY-ROOT")
	e.line(0, "MOVE SPACES TO "+f.Field)
	e.line(0, fmt.Sprintf("IF DC-LEN > %d", f.Size))
	e.problem(1, fmt.Sprintf("path does not fit in %s (PIC X(%d))", f.Field, f.Size), "out_of_range")
	e.line(0, "ELSE")
	e.line(1, "MOVE DC-RAW(1:DC-LEN) TO "+f.Field)
	e.line(0, "END-IF.")
}

// deprecationWarning prints, when a deprecated variable is set, a
// warning naming it and its message, never its value (SPEC section 4.2).
// It is not a problem: the variable still loads and is still checked.
func deprecationWarning(e *emitter, ind int, v *Var) {
	if v.Deprecated == "" {
		return
	}
	msg := "docuconf: warning: " + v.Env + " is deprecated"
	if v.ReplacedBy != "" {
		msg += " (replaced by " + v.ReplacedBy + ")"
	}
	e.display(ind, msg+": "+v.Deprecated)
}

// display writes DISPLAY text UPON SYSERR, splitting a long literal.
func (e *emitter) display(ind int, text string) {
	parts := chunks(text, width-len(stmt)-4*ind-12)
	e.line(ind, "DISPLAY "+cobolLiteral(parts[0]))
	for _, p := range parts[1:] {
		e.line(ind, "    "+cobolLiteral(p))
	}
	e.line(ind, "    UPON SYSERR")
	e.line(ind, "END-DISPLAY")
}

// A grammar is SPEC section 5's exact form of a type's wire value, which
// a value must match before the loader converts it: NUMVAL and the
// duration paragraphs accept more (spaces, .5, lower-case ISO 8601).
// generate compiles it like a @pattern, and the loader holds one
// paragraph per grammar its variables use.
type grammar struct {
	key, para, re, msg string
}

var grammars = []grammar{
	{"bool", "DC-G-BOOL", `^([Tt][Rr][Uu][Ee]|[Ff][Aa][Ll][Ss][Ee])$`, "is not true or false"},
	{"int", "DC-G-INT", `^[+-]?[0-9]+$`, "is not an integer"},
	{"float", "DC-G-FLOAT", `^[+-]?[0-9]+(\.[0-9]+)?([eE][+-]?[0-9]+)?$`, "is not a number"},
	{"go", "DC-G-GO", `^[+-]?(0|(([0-9]+(\.[0-9]*)?|\.[0-9]+)(ns|us|µs|μs|ms|s|m|h))+)$`,
		"is not a duration such as 1m30s"},
	{"iso8601", "DC-G-ISO8601", isoGrammar(), "is not an ISO 8601 duration such as PT90S"},
	{"seconds", "DC-G-SECONDS", `^[0-9]+(\.[0-9]+)?$`, "is not a number of seconds such as 90 or 1.5"},
	{"timespan", "DC-G-TIMESPAN", `^([0-9]+\.)?([01]?[0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9](\.[0-9]{1,7})?$`,
		"is not a duration of the form [d.]hh:mm:ss[.fff]"},
}

// isoGrammar is P[nD][T[nH][nM][nS]], with at least one component and,
// after a T, at least one time component.
func isoGrammar() string {
	n := `[0-9]+([.,][0-9]+)?`
	t := `T(` + n + `H(` + n + `M)?(` + n + `S)?|` + n + `M(` + n + `S)?|` + n + `S)`
	return `^P(` + n + `D(` + t + `)?|` + t + `)$`
}

// grammarOf is the grammar v's values (or items) must match, or nil.
func grammarOf(v *Var) *grammar {
	typ := v.Type
	if v.isList() {
		typ = v.Items
	}
	key := typ
	if typ == tDuration {
		key = v.Encoding
	}
	for i := range grammars {
		if grammars[i].key == key {
			return &grammars[i]
		}
	}
	return nil
}

// grammars returns the grammars the loader's variables use, in a fixed
// order.
func (c *Config) grammars() []*grammar {
	used := map[string]bool{}
	for _, v := range c.Vars {
		if g := grammarOf(v); g != nil {
			used[g.key] = true
		}
	}
	var out []*grammar
	for i := range grammars {
		if used[grammars[i].key] {
			out = append(out, &grammars[i])
		}
	}
	return out
}

func (g *grammar) emit(e *emitter) {
	prog, err := compileRE2(g.re)
	if err != nil || prog == nil {
		panic(fmt.Sprintf("grammar %s: %v", g.key, err))
	}
	e.comment(fmt.Sprintf("DC-RX-OK is \"Y\" when DC-RAW(1:DC-LEN) is a %s value", g.key))
	e.comment("in the exact form SPEC section 5 gives it.")
	e.para(g.para)
	e.table(0, prog.insts, "DC-RX-PROG")
	if prog.ranges != "" {
		e.table(0, prog.ranges, "DC-RX-RANGES")
	}
	e.line(0, fmt.Sprintf("MOVE %d TO DC-RX-N", prog.n))
	e.line(0, fmt.Sprintf("MOVE %d TO DC-RX-START", prog.start))
	e.line(0, "PERFORM DC-RX-MATCH.")
}
