package gen

import (
	"fmt"
	"math/big"
	"strings"

	"github.com/docuconf/docuconf-cobol/copybooks"
)

// The loader is written so that it compiles in both fixed and free
// format: code in columns 8 to 72, *> comments, no continuation lines.
const (
	area  = "       "     // column 8
	stmt  = "           " // column 12
	width = 72
)

type emitter struct {
	b strings.Builder
}

// line writes a statement, breaking it at spaces outside literals when
// it would pass column 72.
func (e *emitter) line(indent int, s string) {
	pad := stmt + strings.Repeat("    ", indent)
	for len(pad)+len(s) > width {
		cut := -1
		inLit := false
		for i := 0; i < len(s) && len(pad)+i <= width; i++ {
			switch {
			case s[i] == '"':
				inLit = !inLit
			case s[i] == ' ' && !inLit:
				cut = i
			}
		}
		if cut <= 0 {
			break // nothing to break at; Loader reports the long line
		}
		e.b.WriteString(pad + s[:cut] + "\n")
		s = s[cut+1:]
		if !strings.HasPrefix(pad, stmt+strings.Repeat("    ", indent)+"  ") {
			pad += "  "
		}
	}
	e.b.WriteString(pad + s + "\n")
}

func (e *emitter) para(name string) {
	e.b.WriteString(area + name + ".\n")
}

func (e *emitter) comment(s string) {
	e.b.WriteString(strings.TrimRight("      *> "+s, " ") + "\n")
}

// move writes MOVE literal TO target, splitting a long literal into
// parts joined with &.
func (e *emitter) move(indent int, value, target string) {
	if value == "" {
		e.line(indent, "MOVE SPACES TO "+target)
		return
	}
	col := len(stmt) + 4*indent
	one := "MOVE " + cobolLiteral(value) + " TO " + target
	if col+len(one) <= width {
		e.line(indent, one)
		return
	}
	parts := chunks(value, width-col-8)
	for i, p := range parts {
		if i == 0 {
			e.line(indent, "MOVE "+cobolLiteral(p))
		} else {
			e.line(indent, "  & "+cobolLiteral(p))
		}
	}
	e.line(indent, "  TO "+target)
}

// problem writes the statements that report a problem.
func (e *emitter) problem(indent int, msg, code string) {
	e.move(indent, msg, "DC-MSG")
	e.line(indent, fmt.Sprintf("MOVE %q TO DC-CODE", code))
	e.line(indent, "PERFORM DC-PROBLEM")
}

// cobolLiteral quotes s, doubling quotes inside.
func cobolLiteral(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

// chunks splits s into pieces of at most n bytes once quoted, keeping
// UTF-8 sequences whole, and after a space where there is one.
func chunks(s string, n int) []string {
	out := rawChunks(s, n)
	for i := 0; i+1 < len(out); i++ {
		if j := strings.LastIndexByte(out[i], ' '); j > 0 && j < len(out[i])-1 {
			moved := out[i][j+1:]
			if len(moved)+len(out[i+1]) <= n {
				out[i], out[i+1] = out[i][:j+1], moved+out[i+1]
			}
		}
	}
	return out
}

func rawChunks(s string, n int) []string {
	var out []string
	var cur strings.Builder
	size := 0
	for _, r := range s {
		w := len(string(r))
		if r == '"' {
			w = 2
		}
		if size+w > n && cur.Len() > 0 {
			out = append(out, cur.String())
			cur.Reset()
			size = 0
		}
		cur.WriteRune(r)
		size += w
	}
	return append(out, cur.String())
}

func picText(v *Var) string {
	p := v.Pic
	switch {
	case v.Double:
		return "floating-point"
	case p.Alpha:
		return fmt.Sprintf("PIC X(%d)", p.Size)
	}
	s := ""
	if p.Signed {
		s = "S"
	}
	s += fmt.Sprintf("9(%d)", p.IntDigits)
	if p.Frac > 0 {
		s += fmt.Sprintf("V9(%d)", p.Frac)
	}
	return "PIC " + s
}

// Loader returns the COBOL source of the loader program.
func (c *Config) Loader() ([]byte, error) {
	for _, v := range c.Vars {
		for _, d := range v.Default {
			for _, r := range d {
				if r < 0x20 {
					return nil, fmt.Errorf("%s:%d: %s: a default with control characters cannot be written as a COBOL literal", c.Copybook, v.Line, v.Field)
				}
			}
		}
	}
	e := &emitter{}
	e.comment("Code generated by docuconf-cobol. DO NOT EDIT.")
	e.comment("Source: " + c.Copybook + ". Change the copybook and run")
	e.comment("docuconf-cobol generate again.")
	e.comment("")
	e.comment(fmt.Sprintf("CALL %q USING %s reads the", c.Program, c.Record))
	e.comment("environment into the record and converts each value. On a")
	e.comment("problem it prints one line per problem on stderr and sets")
	e.comment("RETURN-CODE to 1. Run the program under docuconf exec, which")
	e.comment("checks every rule in contract.cue before the program starts.")
	e.b.WriteString(area + "IDENTIFICATION DIVISION.\n")
	e.b.WriteString(area + "PROGRAM-ID. " + c.Program + ".\n")
	e.b.WriteString(area + "DATA DIVISION.\n")
	e.b.WriteString(area + "WORKING-STORAGE SECTION.\n")
	e.b.WriteString(copybooks.WorkingStorage)
	e.b.WriteString(area + "LINKAGE SECTION.\n")
	e.b.WriteString(area + "COPY " + cobolLiteral(c.Copybook) + ".\n")
	e.b.WriteString(area + "PROCEDURE DIVISION USING " + c.Record + ".\n")
	e.para("DC-MAIN")
	e.line(0, "MOVE 0 TO DC-PROBLEMS")
	for i := range c.Vars {
		e.line(0, fmt.Sprintf("PERFORM DC-VAR-%d", i+1))
	}
	for i := range c.Files {
		e.line(0, fmt.Sprintf("PERFORM DC-FILE-%d", i+1))
	}
	e.line(0, "IF DC-PROBLEMS = 0")
	e.line(1, "MOVE 0 TO RETURN-CODE")
	e.line(0, "ELSE")
	e.line(1, "MOVE 1 TO RETURN-CODE")
	e.line(0, "END-IF")
	e.line(0, "GOBACK.")
	for i, v := range c.Vars {
		e.b.WriteByte('\n')
		c.loadVar(e, i+1, v)
	}
	for i, f := range c.Files {
		e.b.WriteByte('\n')
		loadFile(e, i+1, f)
	}
	e.b.WriteByte('\n')
	e.b.WriteString(copybooks.Procedures)
	e.b.WriteString(area + "END PROGRAM " + c.Program + ".\n")
	out := e.b.String()
	for i, l := range strings.Split(out, "\n") {
		if len(l) > width {
			return nil, fmt.Errorf("internal error: generated line %d is longer than 72 columns: %s", i+1, l)
		}
	}
	return []byte(out), nil
}

func (c *Config) loadVar(e *emitter, n int, v *Var) {
	e.comment(fmt.Sprintf("%s into %s", v.Env, v.Field))
	e.para(fmt.Sprintf("DC-VAR-%d", n))
	e.move(0, v.Env, "DC-NAME")
	if v.Type == tList {
		c.loadList(e, n, v)
		return
	}
	e.line(0, "PERFORM DC-GET-ENV")
	if v.Type != tString {
		// An empty value is unset for every type but string.
		e.line(0, "IF DC-LEN = 0")
		e.line(1, `MOVE "N" TO DC-SET`)
		e.line(0, "END-IF")
	}
	e.line(0, `IF DC-SET = "N"`)
	e.line(1, "INITIALIZE "+v.Field)
	switch {
	case v.Required:
		e.problem(1, "is required but not set", "missing_required")
	case v.Default != nil:
		defaultScalar(e, 1, v, v.Field)
	}
	if v.Present != "" {
		if v.Default != nil {
			e.line(1, `MOVE "Y" TO `+v.Present)
		} else {
			e.line(1, `MOVE "N" TO `+v.Present)
		}
	}
	e.line(0, "ELSE")
	storeScalar(e, 1, v, v.Field, v.Field)
	if v.Present != "" {
		e.line(1, `MOVE "Y" TO `+v.Present)
	}
	e.line(0, "END-IF.")
}

// defaultScalar moves the default into target.
func defaultScalar(e *emitter, ind int, v *Var, target string) {
	d := v.Default[0]
	switch v.Type {
	case tString, tURL, tEnum, tJSON:
		e.move(ind, d, target)
	case tInt, tFloat:
		e.line(ind, "MOVE "+d+" TO "+target)
	case tBool:
		e.line(ind, "MOVE "+boolValue(v, strings.EqualFold(d, "true"))+" TO "+target)
	case tDuration:
		e.line(ind, "MOVE "+durationValue(d, v.UnitNs)+" TO "+target)
	}
}

func boolValue(v *Var, b bool) string {
	switch {
	case v.Pic.Alpha && b:
		return `"Y"`
	case v.Pic.Alpha:
		return `"N"`
	case b:
		return "1"
	}
	return "0"
}

// durationValue is a duration default in the field's unit.
func durationValue(d string, unitNs int64) string {
	ns, _ := parseGoDuration(d)
	r := new(big.Rat).SetFrac(big.NewInt(ns), big.NewInt(unitNs))
	if r.IsInt() {
		return r.Num().String()
	}
	return strings.TrimRight(r.FloatString(9), "0")
}

// storeScalar converts DC-RAW(1:DC-LEN) and stores it in target. label
// names the field in messages.
func storeScalar(e *emitter, ind int, v *Var, target, label string) {
	typ := v.Type
	if typ == tList {
		typ = v.Items
	}
	fits := fmt.Sprintf("does not fit in %s (%s)", label, picText(v))
	switch typ {
	case tString, tURL, tEnum, tJSON:
		e.line(ind, fmt.Sprintf("IF DC-LEN > %d", v.Pic.Size))
		e.problem(ind+1, fits, "out_of_range")
		e.line(ind, "ELSE")
		e.line(ind+1, "MOVE SPACES TO "+target)
		e.line(ind+1, "IF DC-LEN > 0")
		e.line(ind+2, "MOVE DC-RAW(1:DC-LEN) TO "+target)
		e.line(ind+1, "END-IF")
		if typ == tEnum {
			e.line(ind+1, "EVALUATE "+target)
			for _, val := range v.Values {
				e.line(ind+2, "WHEN "+cobolLiteral(val))
			}
			e.line(ind+3, "CONTINUE")
			e.line(ind+2, "WHEN OTHER")
			e.problem(ind+3, "is not one of the enum's values", "not_in_enum")
			e.line(ind+1, "END-EVALUATE")
		}
		e.line(ind, "END-IF")
	case tInt:
		e.line(ind, "PERFORM DC-PARSE-INT")
		e.line(ind, `IF DC-OK = "Y"`)
		ind2 := ind + 1
		if !v.Pic.Signed {
			e.line(ind+1, "IF DC-INT < 0")
			e.problem(ind+2, fmt.Sprintf("is negative, and %s is unsigned", label), "out_of_range")
			e.line(ind+1, "ELSE")
			ind2++
		}
		e.line(ind2, "COMPUTE "+target+" = DC-INT")
		e.line(ind2+1, "ON SIZE ERROR")
		e.problem(ind2+2, fits, "out_of_range")
		e.line(ind2, "END-COMPUTE")
		if !v.Pic.Signed {
			e.line(ind+1, "END-IF")
		}
		e.line(ind, "END-IF")
	case tFloat:
		num := "FUNCTION NUMVAL-F(DC-TMP(1:DC-TMP-LEN))"
		e.line(ind, "PERFORM DC-PARSE-FLOAT")
		e.line(ind, `IF DC-OK = "Y"`)
		ind2 := ind + 1
		if !v.Pic.Signed {
			e.line(ind+1, "IF "+num+" < 0")
			e.problem(ind+2, fmt.Sprintf("is negative, and %s is unsigned", label), "out_of_range")
			e.line(ind+1, "ELSE")
			ind2++
		}
		e.line(ind2, "COMPUTE "+target+" =")
		e.line(ind2+1, num)
		e.line(ind2+1, "ON SIZE ERROR")
		e.problem(ind2+2, fits, "out_of_range")
		e.line(ind2, "END-COMPUTE")
		if !v.Double {
			e.line(ind2, `IF DC-OK = "Y" AND `+target)
			e.line(ind2+1, "NOT = "+num)
			e.problem(ind2+1, fmt.Sprintf("has more decimal places than %s holds", label), "out_of_range")
			e.line(ind2, "END-IF")
		}
		if !v.Pic.Signed {
			e.line(ind+1, "END-IF")
		}
		e.line(ind, "END-IF")
	case tBool:
		e.line(ind, "PERFORM DC-PARSE-BOOL")
		e.line(ind, `IF DC-OK = "Y"`)
		if v.Pic.Alpha {
			e.line(ind+1, "MOVE DC-BOOL TO "+target)
		} else {
			e.line(ind+1, `IF DC-BOOL = "Y"`)
			e.line(ind+2, "MOVE 1 TO "+target)
			e.line(ind+1, "ELSE")
			e.line(ind+2, "MOVE 0 TO "+target)
			e.line(ind+1, "END-IF")
		}
		e.line(ind, "END-IF")
	case tDuration:
		e.line(ind, fmt.Sprintf("MOVE %q TO DC-ENC", v.Encoding))
		e.line(ind, "PERFORM DC-PARSE-DURATION")
		e.line(ind, `IF DC-OK = "Y"`)
		e.line(ind+1, fmt.Sprintf("MOVE %d TO DC-UNIT-NS", v.UnitNs))
		e.line(ind+1, "COMPUTE DC-CHK = DC-NS / DC-UNIT-NS")
		ind2 := ind + 1
		if !v.Pic.Signed {
			e.line(ind+1, "IF DC-CHK < 0")
			e.problem(ind+2, fmt.Sprintf("is negative, and %s is unsigned", label), "out_of_range")
			e.line(ind+1, "ELSE")
			ind2++
		}
		e.line(ind2, "COMPUTE "+target+" = DC-CHK")
		e.line(ind2+1, "ON SIZE ERROR")
		e.problem(ind2+2, fits, "out_of_range")
		e.line(ind2, "END-COMPUTE")
		e.line(ind2, `IF DC-OK = "Y" AND `+target)
		e.line(ind2+1, "NOT = DC-CHK")
		e.problem(ind2+1, fmt.Sprintf("is finer than the %s %s counts in", v.Unit, label), "out_of_range")
		e.line(ind2, "END-IF")
		if !v.Pic.Signed {
			e.line(ind+1, "END-IF")
		}
		e.line(ind, "END-IF")
	}
}

func (c *Config) loadList(e *emitter, n int, v *Var) {
	item := v.Field + "(DC-K)"
	e.line(0, fmt.Sprintf("MOVE %d TO DC-ITEM-LIMIT", v.Occurs))
	if v.Encoding == "indexed" {
		e.line(0, "PERFORM DC-READ-INDEXED")
	} else {
		e.line(0, "PERFORM DC-GET-ENV")
		e.line(0, "IF DC-LEN = 0")
		e.line(1, `MOVE "N" TO DC-SET`)
		e.line(0, "END-IF")
	}
	// Every slot is cleared, with the count at the table's size so a
	// DEPENDING ON table can be addressed in full.
	e.line(0, fmt.Sprintf("MOVE %d TO %s", v.Occurs, v.Count))
	e.line(0, "PERFORM VARYING DC-K FROM 1 BY 1")
	e.line(2, fmt.Sprintf("UNTIL DC-K > %d", v.Occurs))
	e.line(1, "INITIALIZE "+item)
	e.line(0, "END-PERFORM")
	e.line(0, `IF DC-SET = "N"`)
	e.line(1, "MOVE 0 TO DC-ITEM-COUNT")
	switch {
	case v.Required:
		e.problem(1, "is required but not set", "missing_required")
	case v.Default != nil:
		for i, d := range v.Default {
			t := fmt.Sprintf("%s(%d)", v.Field, i+1)
			if v.Items == tInt {
				e.line(1, "MOVE "+d+" TO "+t)
			} else {
				e.move(1, d, t)
			}
		}
		e.line(1, fmt.Sprintf("MOVE %d TO DC-ITEM-COUNT", len(v.Default)))
	}
	if v.Present != "" {
		e.line(1, fmt.Sprintf(`MOVE %q TO %s`, map[bool]string{true: "Y", false: "N"}[v.Default != nil], v.Present))
	}
	e.line(0, "ELSE")
	switch v.Encoding {
	case "csv":
		e.move(1, v.Separator, "DC-SEP")
		e.line(1, fmt.Sprintf("MOVE %d TO DC-SEP-LEN", len(v.Separator)))
		e.line(1, "PERFORM DC-SPLIT-CSV")
	case "json":
		e.line(1, "PERFORM DC-SPLIT-JSON")
	}
	e.line(1, `IF DC-OK = "Y"`)
	e.line(2, "PERFORM VARYING DC-K FROM 1 BY 1")
	e.line(4, "UNTIL DC-K > DC-ITEM-COUNT")
	e.line(3, fmt.Sprintf("PERFORM DC-VAR-%d-ITEM", n))
	e.line(2, "END-PERFORM")
	e.line(1, "ELSE")
	e.line(2, "MOVE 0 TO DC-ITEM-COUNT")
	e.line(1, "END-IF")
	if v.Present != "" {
		e.line(1, `MOVE "Y" TO `+v.Present)
	}
	e.line(0, "END-IF")
	e.line(0, "MOVE DC-ITEM-COUNT TO "+v.Count+".")

	e.b.WriteByte('\n')
	e.para(fmt.Sprintf("DC-VAR-%d-ITEM", n))
	kind := map[string]string{tString: "S", tInt: "N"}[v.Items]
	if v.Encoding == "json" {
		e.line(0, fmt.Sprintf("IF DC-ITEM-KIND(DC-K) NOT = %q", kind))
		e.problem(1, "has an item of the wrong JSON type", "invalid_type")
		e.line(0, "ELSE")
	}
	e.line(0, "PERFORM DC-ITEM-TO-RAW")
	storeScalar(e, 0, v, item, v.Field)
	if v.Encoding == "json" {
		e.line(0, "END-IF")
	}
	e.b.WriteString(stmt + ".\n")
}

func loadFile(e *emitter, n int, f *FileInput) {
	e.comment(fmt.Sprintf("file input %s: its path into %s", f.Name, f.Field))
	e.para(fmt.Sprintf("DC-FILE-%d", n))
	if f.PathEnv != "" {
		e.move(0, f.PathEnv, "DC-NAME")
		e.line(0, "PERFORM DC-GET-ENV")
		e.line(0, `IF DC-SET = "N" OR DC-LEN = 0`)
		e.line(1, "MOVE SPACES TO DC-RAW")
		e.move(1, f.Path, "DC-RAW")
		e.line(1, fmt.Sprintf("MOVE %d TO DC-LEN", len(f.Path)))
		e.line(0, "END-IF")
	} else {
		e.line(0, "MOVE SPACES TO DC-RAW")
		e.move(0, f.Path, "DC-RAW")
		e.line(0, fmt.Sprintf("MOVE %d TO DC-LEN", len(f.Path)))
	}
	e.move(0, f.Name, "DC-BASE")
	e.line(0, "PERFORM DC-BASE-NAME")
	e.line(0, `MOVE "Y" TO DC-OK`)
	e.line(0, "PERFORM DC-APPLY-ROOT")
	e.line(0, "MOVE SPACES TO "+f.Field)
	e.line(0, fmt.Sprintf("IF DC-LEN > %d", f.Size))
	e.problem(1, fmt.Sprintf("path does not fit in %s (PIC X(%d))", f.Field, f.Size), "out_of_range")
	e.line(0, "ELSE")
	e.line(1, "MOVE DC-RAW(1:DC-LEN) TO "+f.Field)
	e.line(0, "END-IF.")
}
